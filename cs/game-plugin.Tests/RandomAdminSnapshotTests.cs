using CaorenCup.Contracts;
using CaorenCup.Gamemodes.Random;
using Xunit;

namespace CaorenCup.GamePlugin.Tests;

public sealed class RandomAdminSnapshotTests
{
    private static RandomPlayerIdentity Identity(string id = "p", string name = "玩家", int team = 2) => new(id, name, team);

    [Fact]
    public void Denied_administrator_never_enumerates_or_reads_the_match()
    {
        var checkedRoot = false;
        var readSnapshot = false;
        bool Root() { checkedRoot = true; return true; }
        RandomAdminView Read() { readSnapshot = true; return new(0, false, []); }
        Assert.Null(RandomAdminSnapshotAccess.Read(false, Root, Read));
        Assert.False(checkedRoot);
        Assert.False(readSnapshot);
        Assert.Null(RandomAdminSnapshotAccess.Read(true, () => false, Read));
        Assert.False(readSnapshot);
        Assert.NotNull(RandomAdminSnapshotAccess.Read(true, Root, Read));
        Assert.True(checkedRoot);
        Assert.True(readSnapshot);
    }

    [Fact]
    public void Inspection_does_not_create_players_spend_randomness_or_invalidate_a_pending_purchase()
    {
        var draws = 0;
        var match = new RandomMatch(RandomCatalog.Cards.Where(c => c.Quality == "D").ToArray(), shuffle: _ => draws++, roundCoupons: 1);
        match.Start(); match.BeginRound(1, ["p"]); match.ObservePlayer(Identity());
        var before = match.View("p", true)!;
        for (var i = 0; i < 3; i++)
        {
            var snapshot = match.AdminSnapshot([Identity(), Identity("new", "刚加入", 3), Identity("spec", "旁观", 1)]);
            Assert.Equal(3, snapshot.Players.Count);
            Assert.True(snapshot.Players.Single(p => p.SteamId == "p").Participating);
            var newcomer = snapshot.Players.Single(p => p.SteamId == "new");
            Assert.False(newcomer.Participating);
            Assert.Equal(0, newcomer.Coupons);
            Assert.Empty(newcomer.Owned);
            Assert.False(snapshot.Players.Single(p => p.SteamId == "spec").Participating);
        }
        Assert.Equal(3, draws);
        Assert.Single(match.AdminSnapshot([]).Players); // Viewing new/spec must not retain them as match participants.
        var after = match.View("p", true)!;
        Assert.Equal(before.Revision, after.Revision);
        Assert.Equal(before.Coupons, after.Coupons);
        Assert.Equal(before.Offers.Select(card => card.Key), after.Offers.Select(card => card.Key));
        Assert.True(match.Purchase("p", RandomCatalog.Reload, before.Revision, true).Success);
    }

    [Fact]
    public void Offline_previous_round_flags_are_projected_without_preparing_the_next_round()
    {
        var draws = 0;
        var cards = Enumerable.Range(1, 6).Select(i => new BuffDefinition("k" + i, "D-" + i, "卡" + i, "防御", "简", "详", 3)).ToArray();
        var match = new RandomMatch(cards, _ => draws++, roundCoupons: 1);
        match.Start(); match.BeginRound(1, ["p"]); match.ObservePlayer(Identity());
        Assert.True(match.Exchange("p", match.View("p", true)!.Revision, true, _ => true).Success);
        Assert.True(match.Reroll("p", match.View("p", true)!.Revision, true).Success);
        var offered = match.View("p", true)!;
        Assert.True(match.Purchase("p", offered.Offers[0].Key, offered.Revision, true).Success);
        var used = Assert.Single(match.AdminSnapshot([Identity()]).Players);
        Assert.True(used.PurchasedThisRound);
        Assert.True(used.RerolledThisRound);
        Assert.True(used.ExchangedThisRound);
        Assert.Equal(0, used.Coupons);
        Assert.Single(used.Owned);
        var revision = match.View("p", true)!.Revision;
        match.AdminSnapshot([Identity()]);
        Assert.Equal(revision, match.View("p", true)!.Revision);
        Assert.Equal(6, draws);
        match.EndRound(1); match.BeginRound(2, []);
        var offline = Assert.Single(match.AdminSnapshot([]).Players);
        Assert.False(offline.Connected);
        Assert.Equal("玩家", offline.Name);
        Assert.Equal(2, offline.Team);
        Assert.True(offline.Participating);
        Assert.False(offline.PurchasedThisRound);
        Assert.False(offline.RerolledThisRound);
        Assert.False(offline.ExchangedThisRound);
        Assert.Equal(0, offline.Coupons); // No historical reward or reset is generated by inspection.
        Assert.Single(offline.Owned);
        Assert.Equal(6, draws);
        match.View("p", true); // Only the player's own return performs existing lazy round preparation.
        Assert.Equal(9, draws);
    }

    [Fact]
    public void Online_identity_is_current_but_queries_do_not_write_identity_metadata()
    {
        var match = new RandomMatch(RandomCatalog.Cards.Where(c => c.Quality == "D").ToArray(), roundCoupons: 1); match.Start(); match.BeginRound(1, ["p"]);
        match.ObservePlayer(Identity(name: "此前名字", team: 2));
        var online = Assert.Single(match.AdminSnapshot([Identity(name: "新名字", team: 1)]).Players);
        Assert.Equal("新名字", online.Name);
        Assert.Equal(1, online.Team);
        Assert.True(online.Connected);
        Assert.False(online.Participating);
        var offline = Assert.Single(match.AdminSnapshot([]).Players);
        Assert.Equal("此前名字", offline.Name);
        Assert.Equal(2, offline.Team);
        match.ObservePlayer(Identity(name: "断线时名字", team: 3));
        offline = Assert.Single(match.AdminSnapshot([]).Players);
        Assert.Equal("断线时名字", offline.Name);
        Assert.Equal(3, offline.Team);
    }

    [Fact]
    public void Buff_snapshots_are_detached_and_stop_clears_only_retained_match_participants()
    {
        var match = new RandomMatch(RandomCatalog.Cards.Where(c => c.Quality == "D").ToArray(), roundCoupons: 1); match.Start(); match.BeginRound(1, ["p"]); match.ObservePlayer(Identity());
        var first = match.View("p", true)!;
        Assert.True(match.Purchase("p", RandomCatalog.Reload, first.Revision, true).Success);
        var snapshot = match.AdminSnapshot([Identity()]);
        var row = Assert.Single(snapshot.Players);
        Assert.Equal(1, Assert.Single(row.Owned).Level);
        Assert.Throws<NotSupportedException>(() => ((IList<RandomBuffView>)row.Owned).Clear());
        match.EndRound(1); match.BeginRound(2, ["p"]);
        Assert.True(match.Purchase("p", RandomCatalog.Reload, match.View("p", true)!.Revision, true).Success);
        Assert.Equal(1, Assert.Single(row.Owned).Level);
        Assert.Equal(2, Assert.Single(Assert.Single(match.AdminSnapshot([]).Players).Owned).Level);
        match.Stop();
        Assert.Empty(match.AdminSnapshot([]).Players);
        var stopped = match.AdminSnapshot([Identity("watcher", "管理员", 1)]);
        Assert.False(stopped.Running);
        Assert.Equal(0, stopped.Round);
        var watcher = Assert.Single(stopped.Players);
        Assert.False(watcher.Participating);
        Assert.True(watcher.Connected);
        Assert.Empty(watcher.Owned);
        match.Start();
        Assert.Empty(match.AdminSnapshot([]).Players);
    }
}
