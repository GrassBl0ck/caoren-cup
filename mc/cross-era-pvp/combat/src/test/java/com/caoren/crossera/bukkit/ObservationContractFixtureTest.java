package com.caoren.crossera.bukkit;

import static org.junit.jupiter.api.Assertions.*;
import com.caoren.crossera.journal.JsonJournal;
import java.nio.charset.StandardCharsets;
import java.nio.file.*;
import java.util.*;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

/** Synthetic protocol fixtures for the independent Python reader; no Bukkit server or player. */
class ObservationContractFixtureTest {
    @TempDir Path temp;
    private static final String ATTACKER = "00000000-0000-0000-0000-000000000001";
    private static final String VICTIM = "00000000-0000-0000-0000-000000000002";
    private static final String WORLD = "00000000-0000-0000-0000-000000000003";

    @Test void produceGuardedAndInvalidatedContractsWithRealSerializer() throws Exception {
        for (boolean invalidate : List.of(false, true)) {
            String name = invalidate ? "invalidated" : "guarded";
            var journal = JsonJournal.open(temp.resolve(name + ".jsonl"), 16, message -> fail(message));
            var epochs = new ObservationEpochs();
            var stamp = epochs.capture(UUID.fromString(VICTIM));
            var startup = BukkitSnapshots.event("startup", 0);
            startup.put("pluginVersion", "0.1.0-dev"); startup.put("serverVersion", "synthetic-26.3");
            startup.put("javaVersion", "25"); startup.put("backend", "SYNTHETIC_NO_SERVER");
            startup.put("fidelityAccepted", false); startup.put("followupPolicy", ObservationEpochs.POLICY);
            assertTrue(journal.record(startup));
            var hit = BukkitSnapshots.event("damage_event", 10);
            hit.put("eventId", 1); hit.put("victimObservationEpoch", stamp.id());
            hit.put("cause", "ENTITY_ATTACK"); hit.put("cancelled", false);
            hit.put("samplePhase", "MONITOR_EVENT_VALUES_NOT_ACTUAL_HEALTH_LOSS");
            hit.put("inputProvenance", "BUKKIT_EVENT_NATIVE_OR_SYNTHETIC_UNDETERMINED");
            hit.put("eventBaseDamage", 3); hit.put("eventFinalDamage", 3);
            hit.put("attacker", syntheticPlayer(ATTACKER, "old"));
            hit.put("victim", syntheticPlayer(VICTIM, "modern"));
            assertTrue(journal.record(hit));
            if (invalidate) epochs.invalidate(UUID.fromString(VICTIM), ObservationEpochs.Reason.RESPAWN);
            var follow = BukkitSnapshots.event("health_followup", 11);
            follow.put("eventId", 1); follow.put("windowTicks", 1);
            follow.put("sameConnectionAndWorld", true); follow.put("isolatedHitGuaranteed", false);
            follow.putAll(stamp.evidence());
            if (stamp.valid()) {
                follow.put("healthBeforeEventCommit", 20); follow.put("healthAtSample", 17);
                follow.put("netHealthDelta", 3); follow.put("netAbsorptionDelta", 0);
                follow.put("deadAtSample", false); follow.put("velocityAtSample", Map.of("x", 0, "y", 0, "z", 0));
            }
            assertTrue(journal.record(follow));
            var shutdown = BukkitSnapshots.event("shutdown", 20);
            shutdown.put("journalBeforeDrain", journal.stats());
            assertTrue(journal.record(shutdown));
            journal.close();
            assertEquals(4L, journal.stats().get("accepted"));
            assertEquals(0L, journal.stats().get("errors"));
            Files.writeString(temp.resolve(name + ".console.txt"),
                    "[草人杯] 日志收尾完成：" + journal.stats() + "\n", StandardCharsets.UTF_8, StandardOpenOption.CREATE_NEW);
        }
        Files.writeString(temp.resolve("SYNTHETIC-ONLY.txt"),
                "Generated by a JUnit test with fabricated inputs. No player, server, vanilla baseline or gameplay evidence.\n",
                StandardCharsets.UTF_8, StandardOpenOption.CREATE_NEW);
        System.out.println("SYNTHETIC_CONTRACT_DIR=" + temp.toAbsolutePath());
    }

    private static Map<String, Object> syntheticPlayer(String uuid, String profile) {
        Map<String, Object> data = new LinkedHashMap<>();
        data.put("uuid", uuid); data.put("world", "synthetic-world"); data.put("worldId", WORLD);
        data.put("profile", profile); data.put("modeset", "ce-" + profile);
        data.put("stored", true); data.put("overrides", false); data.put("verifiedModules", true);
        data.put("effectiveModules", Map.of("synthetic-module", profile.equals("old")));
        data.put("position", Map.of("x", 0, "y", 200, "z", 0, "yaw", 0, "pitch", 0));
        data.put("velocity", Map.of("x", 0, "y", 0, "z", 0));
        data.put("health", 20); data.put("absorption", 0); data.put("lastDamage", 0);
        data.put("noDamageTicks", 0); data.put("maximumNoDamageTicks", 20);
        data.put("attackCooldownObserved", 1); data.put("fallDistance", 0);
        for (String key : List.of("sprinting", "inWater", "climbing", "insideVehicle", "blindness")) data.put(key, false);
        data.put("onGround", true); data.put("effects", List.of());
        data.put("mainHand", Map.of("material", "DIAMOND_SWORD", "amount", 1, "enchanted", false, "durabilityDamage", 0));
        data.put("armourBootsToHelmet", Collections.nCopies(4, Map.of("material", "AIR", "amount", 0)));
        return data;
    }
}
