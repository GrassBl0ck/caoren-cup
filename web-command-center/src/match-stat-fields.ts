const publicStatKeys = [...Object.keys(createEmptyMatchStats()), 'head_shot_kills', 'deathsTraded'];

export function publicMatchStats(stats: unknown) {
    if (!stats || typeof stats !== 'object') return;
    const input = stats as Record<string, unknown>;
    return Object.fromEntries(publicStatKeys.filter(key => Number.isFinite(input[key])).map(key => [key, input[key]]));
}
